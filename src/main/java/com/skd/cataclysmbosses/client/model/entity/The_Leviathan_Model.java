    public Vec3 translateToTongue(Vec3 in, float yawIn) {
        PoseStack modelTranslateStack = new PoseStack();
        modelTranslateStack.mulPose(Axis.YP.rotationDegrees(180.0f - yawIn));
        modelTranslateStack.translate((double)(this.root.rotationPointX / 16.0f), (double)(this.root.rotationPointY / 16.0f), (double)(this.root.rotationPointZ / 16.0f));
        modelTranslateStack.mulPose(Axis.ZN.rotation(this.root.rotateAngleZ));
        modelTranslateStack.mulPose(Axis.YN.rotation(this.root.rotateAngleY));
        modelTranslateStack.mulPose(Axis.XN.rotation(this.root.rotateAngleX));
        modelTranslateStack.translate((double)(this.body.rotationPointX / 16.0f), (double)(this.body.rotationPointY / 16.0f), (double)(this.body.rotationPointZ / 16.0f));
        modelTranslateStack.mulPose(Axis.ZN.rotation(this.body.rotateAngleZ));
        modelTranslateStack.mulPose(Axis.YN.rotation(this.body.rotateAngleY));
        modelTranslateStack.mulPose(Axis.XN.rotation(this.body.rotateAngleX));
        modelTranslateStack.translate((double)(this.Head.rotationPointX / 16.0f), (double)(this.Head.rotationPointY / 16.0f), (double)(this.Head.rotationPointZ / 16.0f));
        modelTranslateStack.mulPose(Axis.ZN.rotation(this.Head.rotateAngleZ));
        modelTranslateStack.mulPose(Axis.YN.rotation(this.Head.rotateAngleY));
        modelTranslateStack.mulPose(Axis.XN.rotation(this.Head.rotateAngleX));
        modelTranslateStack.translate((double)(this.tongue.rotationPointX / 16.0f), (double)(this.tongue.rotationPointY / 16.0f), (double)(this.tongue.rotationPointZ / 16.0f));
        modelTranslateStack.mulPose(Axis.ZN.rotation(this.tongue.rotateAngleZ));
        modelTranslateStack.mulPose(Axis.YN.rotation(this.tongue.rotateAngleY));
        modelTranslateStack.mulPose(Axis.XN.rotation(this.tongue.rotateAngleX));
        Vector4f tongueOffsetVec = new Vector4f((float)in.x, (float)in.y, (float)in.z, 1.0f);
        tongueOffsetVec.mul((Matrix4fc)modelTranslateStack.last().pose());
        Vec3 offset = new Vec3((double)tongueOffsetVec.x(), (double)tongueOffsetVec.y(), (double)tongueOffsetVec.z());
        modelTranslateStack.popPose();
        return offset;
    }

